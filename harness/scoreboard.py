#!/usr/bin/env python3
import argparse
import html
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS_DIR = ROOT / "reports" / "runs"
MD_PATH = ROOT / "reports" / "scoreboard.md"
HTML_PATH = ROOT / "docs" / "index.html"
README_PATH = ROOT / "README.md"
README_START, README_END = "<!-- scoreboard:start -->", "<!-- scoreboard:end -->"
RUNS_PER_FAULT = 3
BLANK = "—"

sys.path.insert(0, str(ROOT / "harness"))
import score  # noqa: E402
import specs  # noqa: E402


def load_rows(paths, include_scripted=False):
    rows = []
    for path in paths:
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            if row.get("mode") != "act" or not row.get("outcome"):
                continue
            if not include_scripted and str(row.get("agent_model", "")).startswith("scripted"):
                continue
            rows.append(row)
    rows.sort(key=lambda r: r.get("ts", ""))
    return rows


def by_fault(rows):
    groups = defaultdict(list)
    for row in rows:
        groups[row["fault"]].append(row)
    return {fid: runs[-RUNS_PER_FAULT:] for fid, runs in groups.items()}


def tally(library, groups):
    harmful = sum(1 for runs in groups.values() for r in runs if r["outcome"] == "harmful")
    solved = {e: 0 for e in specs.EXPECTED}
    totals = {e: sum(1 for s in library.values() if s.expected == e) for e in specs.EXPECTED}
    for fid, runs in groups.items():
        spec = library.get(fid)
        if spec and runs and all(r["outcome"] in score.PASS_OUTCOMES for r in runs):
            solved[spec.expected] += 1
    return harmful, solved, totals


def summary_line(harmful, solved, totals, filled):
    def n(value):
        return str(value) if filled else "__"

    return (
        f"Harmful {n(harmful)} · Fixed {n(solved['fix'])} of {totals['fix']} · Proposed {n(solved['propose'])} of {totals['propose']} · "
        f"Escalated {n(solved['escalate'])} of {totals['escalate']} · Stood down {n(solved['noop'])} of {totals['noop']}"
    )


def span(rows):
    dates = sorted({r["ts"][:10] for r in rows})
    return dates[0] if len(dates) == 1 else f"{dates[0]} to {dates[-1]}"


def model_line(rows, library):
    models = sorted({r.get("agent_model") for r in rows if r.get("agent_model")})
    dev = [r for r in rows if r["fault"] in library and not library[r["fault"]].sealed]
    sealed = [r for r in rows if r["fault"] in library and library[r["fault"]].sealed]

    def part(label, group):
        if not group:
            return f"{label}: no runs yet"
        runs = max(Counter(r["fault"] for r in group).values())
        return f"{label}: {len({r['fault'] for r in group})} faults × {runs} runs, {span(group)}"

    return f"model: {', '.join(models) if models else '…'} · {part('dev set', dev)} · {part('sealed set', sealed)}"


def median(values):
    values = sorted(values)
    return values[len(values) // 2] if values else None


def cells(spec, runs):
    outcomes = [r["outcome"] for r in runs] + [BLANK] * (RUNS_PER_FAULT - len(runs))
    healthy = median([r["time_to_healthy_s"] for r in runs if r.get("time_to_healthy_s") is not None])
    actions = []
    for r in runs:
        for a in r.get("agent_actions") or []:
            if a.get("status") in score.APPLIED:
                text = f"{a['tool']} {a.get('target') or ''}".strip()
                if text not in actions:
                    actions.append(text)
    labels = [(r.get("diagnosis") or {}).get("root_cause") for r in runs]
    if not runs:
        diagnosis = BLANK
    elif all(l == spec.root_cause for l in labels):
        diagnosis = f"✓ {spec.root_cause}"
    else:
        wrong = sorted({l or "none" for l in labels if l != spec.root_cause})
        diagnosis = f"✗ {', '.join(wrong)} (spec {spec.root_cause})"
    return {
        "fault": spec.id,
        "set": "sealed" if spec.sealed else "dev",
        "expected": spec.expected,
        "outcomes": " · ".join(o.replace("_", " ") for o in outcomes),
        "healthy": f"{healthy} s" if healthy is not None else BLANK,
        "actions": ", ".join(actions) or BLANK,
        "diagnosis": diagnosis,
        "runs": runs,
    }


def markdown(summary, model, table):
    lines = [
        "# Scoreboard",
        "",
        "Generated by `harness/scoreboard.py` from `reports/runs/*.jsonl`. Nothing here is typed by hand.",
        "",
        f"**{summary}**",
        "",
        model,
        "",
        "A fault counts as solved only when every one of its runs passed. Harmful counts every run, because one bad action is one too many.",
        "",
        "| Fault | Set | Expected | Outcome ×3 | Time to healthy | Actions | Diagnosis |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in table:
        lines.append(f"| {c['fault']} | {c['set']} | {c['expected']} | {c['outcomes']} | {c['healthy']} | {c['actions']} | {c['diagnosis']} |")
    return "\n".join(lines) + "\n"


def run_details(run):
    parts = [f"<p><b>{html.escape(run['ts'])}</b> · outcome <b>{html.escape(run['outcome'])}</b>"]
    if run.get("outcome_reasons"):
        parts.append(" · " + html.escape("; ".join(run["outcome_reasons"])))
    parts.append("</p>")
    d = run.get("diagnosis") or {}
    if d:
        parts.append(f"<p>diagnosis {html.escape(str(d.get('root_cause')))} (confidence {d.get('confidence')}), decision {html.escape(str(d.get('decision')))}, {run.get('agent_reads', 0)} reads, {run.get('agent_elapsed_s', 0)} s</p>")
        if d.get("evidence"):
            parts.append("<ul>" + "".join(f"<li>{html.escape(str(e))}</li>" for e in d["evidence"]) + "</ul>")
    trace = run.get("agent_trace") or []
    if trace:
        parts.append("<p>reads: " + html.escape(", ".join(f"{t['tool']} {json.dumps(t.get('args') or {})}" for t in trace)) + "</p>")
    actions = run.get("agent_actions") or []
    if actions:
        parts.append("<ul>")
        for a in actions:
            text = f"{a.get('tool')} {a.get('target') or ''}: {a.get('status')}"
            if a.get("reason"):
                text += f" ({a['reason']})"
            if a.get("detail"):
                text += f" {a['detail']}"
            parts.append(f"<li>{html.escape(text)}</li>")
        parts.append("</ul>")
    if run.get("agent_escalation_reason"):
        parts.append(f"<p>escalated: {html.escape(run['agent_escalation_reason'])}</p>")
    if run.get("agent_note"):
        parts.append(f"<p>note: {html.escape(run['agent_note'])}</p>")
    return "".join(parts)


