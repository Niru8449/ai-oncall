def update_readme(block):
    if not README_PATH.is_file():
        return False
    text = README_PATH.read_text()
    if README_START not in text or README_END not in text:
        return False
    head, rest = text.split(README_START, 1)
    _, tail = rest.split(README_END, 1)
    README_PATH.write_text(head + README_START + "\n" + block + "\n" + README_END + tail)
    return True


def main(argv=None):
    parser = argparse.ArgumentParser(description="write the scoreboard from the JSONL run rows")
    parser.add_argument("--include-scripted", action="store_true", help="count rows from the scripted stand-in model (tests only)")
    parser.add_argument("files", nargs="*", help="JSONL files; default: every reports/runs/*.jsonl")
    args = parser.parse_args(argv)
    library = specs.load_library(complete=False)
    rows = load_rows([Path(f) for f in args.files] or sorted(RUNS_DIR.glob("*.jsonl")), args.include_scripted)
    rows = [r for r in rows if r["fault"] in library]
    groups = by_fault(rows)
    harmful, solved, totals = tally(library, groups)
    summary = summary_line(harmful, solved, totals, filled=bool(rows))
    model = model_line(rows, library)
    ordered = sorted(library.values(), key=lambda s: (s.sealed, s.id))
    table = [cells(spec, groups.get(spec.id, [])) for spec in ordered]
    MD_PATH.parent.mkdir(parents=True, exist_ok=True)
    MD_PATH.write_text(markdown(summary, model, table))
    HTML_PATH.parent.mkdir(parents=True, exist_ok=True)
    HTML_PATH.write_text(page(summary, model, table))
    readme = update_readme(f"**{summary}**\n\n{model}\n\nFull table with traces: [reports/scoreboard.md](reports/scoreboard.md) · [docs/index.html](docs/index.html)")
    print(summary)
    print(model)
    print(f"wrote {MD_PATH.relative_to(ROOT)}, {HTML_PATH.relative_to(ROOT)}" + (", README block" if readme else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
